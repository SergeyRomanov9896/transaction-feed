# ================= CARD NUMBER GENERATOR =================


def test_generates_card_numbers_from_range_of_integers():
    result_gen = card_number_generator(1, 5)
    result = list(result_gen)
    expected = [
        "0000 0000 0000 0001",
        "0000 0000 0000 0002",
        "0000 0000 0000 0003",
        "0000 0000 0000 0004",
        "0000 0000 0000 0005",
    ]
    assert result == expected


